import { fileURLToPath } from "node:url";
import { z } from "zod";

/** Browser entry for the visitor runtime served at `/_ryu/runtime.js`. */
export const visitorEntry = fileURLToPath(
	new URL("../../ui/src/visitor.ts", import.meta.url)
);
/** The checked-in generated module the sidecar imports. */
export const visitorBundlePath = fileURLToPath(
	new URL("./visitor-bundle.ts", import.meta.url)
);
const workspaceManifest = fileURLToPath(
	new URL("../../../../package.json", import.meta.url)
);

/** True only in the Ryu workspace, where the shared browser primitives resolve. */
export function canBuildVisitor(): boolean {
	try {
		Bun.resolveSync("@ryu/browser-local-ai/data", visitorEntry);
		return true;
	} catch {
		return false;
	}
}

/**
 * The Bun version the workspace pins. Bundler output differs between Bun
 * releases, so only this version reproduces the checked-in runtime.
 */
export async function pinnedBunVersion(): Promise<string | null> {
	const file = Bun.file(workspaceManifest);
	if (!(await file.exists())) {
		return null;
	}
	const manifest = z
		.object({ packageManager: z.string().optional() })
		.safeParse(await file.json());
	return (
		/^bun@(\d+\.\d+\.\d+)$/.exec(manifest.data?.packageManager ?? "")?.[1] ??
		null
	);
}

/** Builds the generated `visitor-bundle.ts` module text from source. */
export async function buildVisitorModule(): Promise<string> {
	const result = await Bun.build({
		entrypoints: [visitorEntry],
		target: "browser",
		minify: true,
	});
	const output = result.outputs[0];
	if (!(result.success && output)) {
		throw new AggregateError(result.logs, "Visitor runtime build failed");
	}
	const script = await output.text();
	return `// biome-ignore-all lint/suspicious/noTemplateCurlyInString: Generated JavaScript contains template literals.\n// biome-ignore-all format: Generated JavaScript is intentionally emitted as one browser bundle.\n// Generated by sidecar/build.ts. Do not edit.\nexport const visitorScript = ${JSON.stringify(script)};\n`;
}
